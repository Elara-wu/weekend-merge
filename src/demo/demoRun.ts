export function createDemoRun(input: { runId: string; at?: string }): AgentEvent[] {
  const at = input.at ?? new Date().toISOString();

  return [
    { type: "run.started", runId: input.runId, at },
    { type: "step.started", step: "ANALYZE", at },
    { type: "step.started", step: "GATHER", at },
    {
      type: "tool.completed",
      tool: "get_weather",
      summary: { forecast: "15:00 后有小雨", temperatureC: 17 },
      durationMs: 240,
      source: "Open-Meteo demo fixture",
    },
    {
      type: "tool.completed",
      tool: "search_places",
      summary: { matched: 12, excluded: 8 },
      durationMs: 18,
      source: "Shanghai places fixture",
    },
    {
      type: "tool.completed",
      tool: "estimate_route",
      summary: { shortestKm: 1.8, longestKm: 2.8 },
      durationMs: 11,
      source: "Local route estimator",
    },
    {
      type: "tool.completed",
      tool: "calculate_budget",
      summary: { lowest: 238, highest: 286, limit: 300 },
      durationMs: 4,
      source: "Deterministic budget calculator",
    },
    { type: "step.started", step: "PROPOSE", at },
    ...candidates.map<AgentEvent>((plan) => ({ type: "plan.proposed", plan })),
    {
      type: "run.completed",
      result: {
        runId: input.runId,
        consensus,
        candidateIds: candidates.map((plan) => plan.id),
      },
    },
  ];
}
